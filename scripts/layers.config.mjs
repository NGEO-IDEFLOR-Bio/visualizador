/** Categorias institucionais do zoneamento (mesma lógica do visualizador antigo). */
export function zonaCategory(zona) {
  const z = String(zona || '').toLowerCase();
  if (z.includes('preserv') || z.includes('nula') || z.includes('intensa preserv')) return 'preservacao';
  if (z.includes('conserv') || z.includes('manejo')) return 'conservacao';
  if (z.includes('amorteciment')) return 'amortecimento';
  if (z.includes('moderad') || z.includes('baixo impacto') || z.includes('extensiv')) return 'uso_moderado';
  if (z.includes('intensiv') || z.includes('populacion') || z.includes('comunit') || z.includes('morador')) return 'uso_intensivo';
  if (z.includes('produ') || z.includes('alta') || z.includes('conflit') || z.includes('tempor')) return 'producao';
  if (z.includes('recupera') || z.includes('degradad')) return 'recuperacao';
  if (z.includes('hist') || z.includes('cultur')) return 'historico';
  return 'outro';
}

